/**
 * All non-English languages with legal taglines for PA Medical Assistance Bulletin compliance
 */
export const taglineLanguages = supportedLanguages.filter((l) => l.code !== "en");

/**
 * Comma-separated language codes for Google Translate widget initialization
 */
export const googleTranslateIncludedLanguages = supportedLanguages.map((l) => l.code).join(",");

/**
 * Get language details by Google Translate code
 */
export function getLanguageByCode(code) {
  if (!code) return supportedLanguages[0];
  const normalized = code.toLowerCase();
  return (
    supportedLanguages.find(
      (l) => l.code.toLowerCase() === normalized || l.code.split("-")[0].toLowerCase() === normalized
    ) || supportedLanguages[0]
  );
}

